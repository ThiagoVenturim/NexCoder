from __future__ import annotations

import html

from faccoder_ideation.models import (
    ArchitectureProposal,
    HumanApprovalGate,
    JuryVerdict,
    ResearchSquadReport,
    StructuredIdea,
)


class ReportGenerator:
    """Generates Markdown and HTML executive reports for ideation deliverables."""

    @staticmethod
    def generate_markdown(
        idea: StructuredIdea,
        report: ResearchSquadReport,
        verdict: JuryVerdict,
        architecture: ArchitectureProposal,
        gate: HumanApprovalGate | None = None,
    ) -> str:
        """Generate comprehensive Markdown executive report."""
        gate = gate or HumanApprovalGate()
        gate_status = "Approved" if gate.approved else "Pending Approval"

        lines = [
            f"# Ideation & Diligence Executive Report: {idea.title}",
            "",
            f"**Idea Identifier**: `{idea.id}`",
            f"**Committee Verdict**: **{verdict.verdict.value.upper()}** (Consensus: {verdict.consensus_reached})",
            f"**Human Gate Status**: `{gate_status}`",
            "",
            "---",
            "",
            "## Executive Summary",
            "",
            f"{idea.summary}",
            "",
            f"- **Problem**: {idea.problem}",
            f"- **Value Hypothesis**: {idea.value_hypothesis.proposed_solution}",
            f"- **Key Impact**: {idea.value_hypothesis.key_benefit}",
            "",
            "## Research Squad Findings",
            "",
            (
                f"- **Market (TAM/SAM/SOM)**: {report.market.tam_estimate} / "
                f"{report.market.sam_estimate} / {report.market.som_estimate}"
            ),
            f"- **CAGR**: {report.market.cagr_percentage}%",
            f"- **Direct Competitors**: {', '.join([c.name for c in report.competitors.direct_competitors])}",
            (
                f"- **Recommended Monetization**: {report.pricing.recommended_model} "
                f"({len(report.pricing.pricing_tiers)} tiers)"
            ),
            f"- **Total Cited Sources**: {len(report.all_sources)} verified references",
            "",
            "## Jury Committee Ballots (b90)",
            "",
            "| Juror | Role | Vote | Overall Score | Key Recommendation |",
            "|---|---|---|---|---|",
        ]

        for b in verdict.ballots:
            rec = b.key_recommendations[0] if b.key_recommendations else "Proceed to planning"
            lines.append(f"| {b.juror_name} | {b.role} | **{b.vote.value.upper()}** | {b.overall_score}/5.0 | {rec} |")

        lines.extend(
            [
                "",
                "## Architecture Overview",
                "",
                f"- **System**: {architecture.system_name}",
                f"- **Components**: {len(architecture.components)} modular services",
                f"- **Deployment**: {architecture.deployment_model}",
                "",
                "---",
                "Report generated by faccoder-ideation engine.",
            ]
        )

        return "\n".join(lines)

    @staticmethod
    def generate_html(
        idea: StructuredIdea,
        report: ResearchSquadReport,
        verdict: JuryVerdict,
        architecture: ArchitectureProposal,
        gate: HumanApprovalGate | None = None,
    ) -> str:
        """Generate clean, self-contained HTML executive dashboard report."""
        gate = gate or HumanApprovalGate()
        gate_badge = (
            '<span class="badge badge-success">Approved</span>'
            if gate.approved
            else '<span class="badge badge-warning">Pending Approval</span>'
        )
        verdict_badge = (
            f'<span class="badge badge-verdict badge-{verdict.verdict.value}">{verdict.verdict.value.upper()}</span>'
        )

        ballot_rows = ""
        for b in verdict.ballots:
            rec = html.escape(b.key_recommendations[0] if b.key_recommendations else "None")
            ballot_rows += (
                f"<tr>"
                f"<td><strong>{html.escape(b.juror_name)}</strong><br><small>{html.escape(b.role)}</small></td>"
                f'<td><span class="badge badge-{b.vote.value}">{b.vote.value.upper()}</span></td>'
                f"<td>{b.overall_score:.1f} / 5.0</td>"
                f"<td>{html.escape(b.reasoning[:120])}...</td>"
                f"<td>{rec}</td>"
                f"</tr>"
            )

        sources_rows = ""
        for src in report.all_sources[:8]:
            link = (
                f'<a href="{html.escape(src.url)}" target="_blank" rel="noopener noreferrer">'
                f"<strong>{html.escape(src.title)}</strong></a> "
            )
            sources_rows += (
                f"<li>"
                f"{link}"
                f"<small>({html.escape(src.provider)})</small><br>"
                f'<span class="source-snippet">{html.escape(src.snippet[:160])}...</span>'
                f"</li>"
            )

        components_cards = ""
        for comp in architecture.components:
            components_cards += (
                f'<div class="card">'
                f"<h4>{html.escape(comp.name)}</h4>"
                f"<p>{html.escape(comp.purpose)}</p>"
                f"<p><small><strong>Tech:</strong> {html.escape(', '.join(comp.technology_choices))}</small></p>"
                f"</div>"
            )

        html_template = f"""<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>Ideation Executive Report - {html.escape(idea.title)}</title>
  <style>
    :root {{
      --bg: #0d1117;
      --card-bg: #161b22;
      --border: #30363d;
      --text: #c9d1d9;
      --text-muted: #8b949e;
      --primary: #58a6ff;
      --success: #238636;
      --warning: #d29922;
      --danger: #da3633;
    }}
    body {{
      font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif;
      background: var(--bg);
      color: var(--text);
      line-height: 1.6;
      margin: 0;
      padding: 24px;
    }}
    .container {{
      max-width: 1100px;
      margin: 0 auto;
    }}
    header {{
      border-bottom: 1px solid var(--border);
      padding-bottom: 16px;
      margin-bottom: 24px;
    }}
    h1, h2, h3, h4 {{
      color: #f0f6fc;
      margin-top: 0;
    }}
    .badge {{
      display: inline-block;
      padding: 4px 10px;
      font-size: 12px;
      font-weight: 600;
      border-radius: 20px;
      text-transform: uppercase;
    }}
    .badge-go, .badge-success {{ background: var(--success); color: #fff; }}
    .badge-pivot, .badge-warning {{ background: var(--warning); color: #fff; }}
    .badge-no-go, .badge-danger {{ background: var(--danger); color: #fff; }}
    .badge-verdict {{ font-size: 16px; padding: 6px 16px; }}
    .grid {{
      display: grid;
      grid-template-columns: repeat(auto-fit, minmax(240px, 1fr));
      gap: 16px;
      margin-bottom: 24px;
    }}
    .card {{
      background: var(--card-bg);
      border: 1px solid var(--border);
      border-radius: 8px;
      padding: 16px;
    }}
    table {{
      width: 100%;
      border-collapse: collapse;
      margin-top: 12px;
      background: var(--card-bg);
      border-radius: 8px;
      overflow: hidden;
      border: 1px solid var(--border);
    }}
    th, td {{
      padding: 12px 14px;
      text-align: left;
      border-bottom: 1px solid var(--border);
      font-size: 14px;
    }}
    th {{
      background: #21262d;
      color: #f0f6fc;
      font-weight: 600;
    }}
    a {{ color: var(--primary); text-decoration: none; }}
    a:hover {{ text-decoration: underline; }}
    ul.sources-list {{ padding-left: 20px; }}
    ul.sources-list li {{ margin-bottom: 12px; }}
    .source-snippet {{ font-size: 13px; color: var(--text-muted); }}
  </style>
</head>
<body>
  <div class="container">
    <header>
      <h1>{html.escape(idea.title)}</h1>
      <p style="font-size: 16px; color: var(--text-muted);">{html.escape(idea.summary)}</p>
      <div>
        <strong>Committee Verdict:</strong> {verdict_badge}
        &nbsp;&nbsp;|&nbsp;&nbsp;
        <strong>Human Approval Gate:</strong> {gate_badge}
      </div>
    </header>

    <div class="grid">
      <div class="card">
        <h4>Market Opportunity</h4>
        <p><strong>TAM:</strong> {html.escape(report.market.tam_estimate)}</p>
        <p><strong>SAM:</strong> {html.escape(report.market.sam_estimate)}</p>
        <p><strong>CAGR:</strong> {report.market.cagr_percentage or "N/A"}%</p>
      </div>
      <div class="card">
        <h4>Competitive Defensibility</h4>
        <p><strong>Direct Rivals:</strong> {len(report.competitors.direct_competitors)} tracked</p>
        <p><strong>Moat:</strong> {
            html.escape(report.differentiation.moat_factors[0] if report.differentiation.moat_factors else "High")
        }</p>
      </div>
      <div class="card">
        <h4>Monetization & Pricing</h4>
        <p><strong>Model:</strong> {html.escape(report.pricing.recommended_model.capitalize())}</p>
        <p><strong>Tiers:</strong> {len(report.pricing.pricing_tiers)} options configured</p>
      </div>
      <div class="card">
        <h4>Compliance & Risk</h4>
        <p><strong>Frameworks:</strong> {len(report.legal_privacy.applicable_frameworks)} covered</p>
        <p><strong>Status:</strong> Validated data sovereignty</p>
      </div>
    </div>

    <h2>Jury Committee Evaluation (b90)</h2>
    <p>{html.escape(verdict.summary)}</p>
    <table>
      <thead>
        <tr>
          <th>Juror</th>
          <th>Vote</th>
          <th>Score</th>
          <th>Assessment</th>
          <th>Key Recommendation</th>
        </tr>
      </thead>
      <tbody>
        {ballot_rows}
      </tbody>
    </table>

    <h2 style="margin-top: 32px;">System Architecture</h2>
    <p><strong>Deployment:</strong> {html.escape(architecture.deployment_model)}</p>
    <div class="grid">
      {components_cards}
    </div>

    <h2 style="margin-top: 32px;">Verified Research Citations ({len(report.all_sources)} total)</h2>
    <ul class="sources-list">
      {sources_rows}
    </ul>
  </div>
</body>
</html>"""
        return html_template
