from __future__ import annotations

import asyncio
import logging
from typing import Any

from faccoder_core import FaccoderConfig, call_structured, get_chat_model
from langchain_core.messages import HumanMessage, SystemMessage
from pydantic import BaseModel

from faccoder_agents.engine.blocks.base import BaseBlock
from faccoder_agents.engine.models import BlockResult, BlockStatus

logger = logging.getLogger(__name__)


class PromptBlock(BaseBlock):
    """Executes an LLM call via faccoder-core model registry or injected model."""

    def __init__(
        self,
        name: str,
        tier: str = "medium",
        system_prompt: str = "",
        user_prompt_template: str = "",
        output_key: str = "llm_output",
        schema: type[BaseModel] | None = None,
        model: Any = None,
        config: FaccoderConfig | None = None,
    ) -> None:
        super().__init__(name=name, block_type="prompt")
        self.tier = tier
        self.system_prompt = system_prompt
        self.user_prompt_template = user_prompt_template
        self.output_key = output_key
        self.schema = schema
        self.model = model
        self.config = config

    def _get_model(self) -> Any:
        if self.model is not None:
            return self.model
        cfg = self.config or FaccoderConfig()
        try:
            return get_chat_model(self.tier, config=cfg, tracing=False)
        except Exception as exc:
            logger.debug("Falling back to FakeChatModel offline: %s", exc)
            from faccoder_core.llm.fake import FakeChatModel

            return FakeChatModel(responses=[f"Output generated by {self.name}"])

    def _render_prompts(self, data: dict[str, Any]) -> tuple[str, str]:
        def _safe_format(template: str, values: dict[str, Any]) -> str:
            if not template or not values:
                return template
            try:
                return template.format(**values)
            except (KeyError, IndexError, ValueError):
                res = template
                for k, v in values.items():
                    res = res.replace(f"{{{k}}}", str(v))
                return res

        rendered_sys = _safe_format(self.system_prompt, data)
        rendered_user = _safe_format(self.user_prompt_template, data)
        return rendered_sys, rendered_user

    async def aexecute(self, state: dict[str, Any], context: dict[str, Any] | None = None) -> BlockResult:
        data = state.get("data", {})
        rendered_sys, rendered_user = self._render_prompts(data)
        model = self._get_model()

        try:
            if self.schema is not None:
                combined_prompt = f"{rendered_sys}\n\n{rendered_user}" if rendered_sys else rendered_user
                structured_res = await call_structured(
                    prompt=combined_prompt,
                    schema=self.schema,
                    llm=model,
                    context=self.name,
                )
                output_val = structured_res
            else:
                messages = []
                if rendered_sys:
                    messages.append(SystemMessage(content=rendered_sys))
                messages.append(HumanMessage(content=rendered_user))

                if hasattr(model, "ainvoke"):
                    res = await model.ainvoke(messages)
                else:
                    res = model.invoke(messages)
                output_val = getattr(res, "content", str(res))

            return BlockResult(
                block_name=self.name,
                status=BlockStatus.SUCCESS,
                updates={self.output_key: output_val},
                message=f"Prompt block '{self.name}' executed successfully",
            )
        except Exception as exc:
            return BlockResult(
                block_name=self.name,
                status=BlockStatus.FAILURE,
                error=f"Prompt block '{self.name}' failed: {exc}",
                message=str(exc),
            )

    def execute(self, state: dict[str, Any], context: dict[str, Any] | None = None) -> BlockResult:
        try:
            loop = asyncio.get_running_loop()
        except RuntimeError:
            loop = None

        if loop and loop.is_running():
            # Already inside an event loop
            import concurrent.futures

            with concurrent.futures.ThreadPoolExecutor(max_workers=1) as pool:
                return pool.submit(lambda: asyncio.run(self.aexecute(state, context))).result()
        else:
            return asyncio.run(self.aexecute(state, context))
