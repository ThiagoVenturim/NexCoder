from __future__ import annotations

import time
import uuid
from enum import StrEnum
from typing import Any

from pydantic import BaseModel, Field


class BlockStatus(StrEnum):
    SUCCESS = "success"
    FAILURE = "failure"
    SKIPPED = "skipped"
    WAITING_APPROVAL = "waiting_approval"
    REJECTED = "rejected"
    DRY_RUN = "dry_run"


class ApprovalStatus(StrEnum):
    PENDING = "pending"
    APPROVED = "approved"
    REJECTED = "rejected"
    EXPIRED = "expired"
    DRY_RUN = "dry_run"


class ApprovalRequest(BaseModel):
    """Encapsulates a human approval gate with dry-run support and time-bounded token."""

    token: str = Field(default_factory=lambda: str(uuid.uuid4()))
    action_name: str
    description: str = ""
    payload: dict[str, Any] = Field(default_factory=dict)
    created_at: float = Field(default_factory=time.time)
    expires_at: float = Field(default_factory=lambda: time.time() + 1800.0)  # 30 minutes default
    status: ApprovalStatus = ApprovalStatus.PENDING

    def is_expired(self, current_time: float | None = None) -> bool:
        now = current_time if current_time is not None else time.time()
        return now > self.expires_at

    def matches_token(self, candidate_token: str) -> bool:
        return self.token.strip() == candidate_token.strip()


class BlockResult(BaseModel):
    """Output generated by a block execution."""

    block_name: str
    status: BlockStatus
    updates: dict[str, Any] = Field(default_factory=dict)
    message: str = ""
    error: str | None = None
    next_step: str | None = None
    approval_request: ApprovalRequest | None = None


class PipelineRunResult(BaseModel):
    """Outcome of a full or partial pipeline execution."""

    pipeline_name: str
    status: str
    data: dict[str, Any] = Field(default_factory=dict)
    history: list[dict[str, Any]] = Field(default_factory=list)
    errors: list[str] = Field(default_factory=list)
    approval: ApprovalRequest | None = None
