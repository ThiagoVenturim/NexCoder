from __future__ import annotations

import hashlib
import hmac
import time
import uuid
from enum import StrEnum
from typing import Any

from pydantic import BaseModel, Field


class BlockStatus(StrEnum):
    SUCCESS = "success"
    FAILURE = "failure"
    SKIPPED = "skipped"
    WAITING_APPROVAL = "waiting_approval"
    REJECTED = "rejected"
    DRY_RUN = "dry_run"


class ApprovalStatus(StrEnum):
    PENDING = "pending"
    APPROVED = "approved"
    REJECTED = "rejected"
    EXPIRED = "expired"
    DRY_RUN = "dry_run"


class ApprovalRequest(BaseModel):
    """Encapsulates a human approval gate with dry-run support, state isolation, and timing-safe tokens."""

    block_name: str = ""
    action_name: str
    description: str = ""
    token_hash: str = ""
    token: str | None = None
    payload: dict[str, Any] = Field(default_factory=dict)
    created_at: float = Field(default_factory=time.time)
    expires_at: float = Field(default_factory=lambda: time.time() + 1800.0)  # 30 minutes default
    status: ApprovalStatus = ApprovalStatus.PENDING
    consumed: bool = False

    @classmethod
    def create(
        cls,
        action_name: str,
        block_name: str = "",
        description: str = "",
        payload: dict[str, Any] | None = None,
        ttl_seconds: float = 1800.0,
        status: ApprovalStatus = ApprovalStatus.PENDING,
    ) -> tuple[ApprovalRequest, str]:
        """Generate a new approval request and return (request, raw_token)."""
        raw_token = str(uuid.uuid4())
        token_hash = hashlib.sha256(raw_token.encode("utf-8")).hexdigest()
        now = time.time()
        req = cls(
            block_name=block_name,
            action_name=action_name,
            description=description,
            token_hash=token_hash,
            token=raw_token,
            payload=payload or {},
            created_at=now,
            expires_at=now + ttl_seconds,
            status=status,
            consumed=False,
        )
        return req, raw_token

    def is_expired(self, current_time: float | None = None) -> bool:
        now = current_time if current_time is not None else time.time()
        return now > self.expires_at

    def matches_token(self, candidate_token: str) -> bool:
        """Timing-safe token check using SHA-256 and hmac.compare_digest."""
        if not candidate_token:
            return False
        candidate_hash = hashlib.sha256(str(candidate_token).strip().encode("utf-8")).hexdigest()
        return hmac.compare_digest(self.token_hash, candidate_hash)

    def to_state_dict(self) -> dict[str, Any]:
        """Serialize into pipeline state while keeping raw token hidden from models."""
        data = self.model_dump()
        data["token"] = None
        return data


class BlockResult(BaseModel):
    """Output generated by a block execution."""

    block_name: str
    status: BlockStatus
    updates: dict[str, Any] = Field(default_factory=dict)
    message: str = ""
    error: str | None = None
    next_step: str | None = None
    approval_request: ApprovalRequest | None = None


class PipelineRunResult(BaseModel):
    """Outcome of a full or partial pipeline execution."""

    pipeline_name: str
    status: str
    data: dict[str, Any] = Field(default_factory=dict)
    history: list[dict[str, Any]] = Field(default_factory=list)
    errors: list[str] = Field(default_factory=list)
    approval: ApprovalRequest | None = None
