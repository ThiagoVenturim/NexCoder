class EmailTemplateManager:
    """Registry and renderer for reusable email templates."""

    def __init__(self) -> None:
        self._templates: dict[str, EmailTemplate] = {}
        self._register_defaults()

    def _register_defaults(self) -> None:
        self.register(
            EmailTemplate(
                name="report_delivery",
                description="Delivery of NexDash engineering, productivity, or sprint reports with attachments.",
                subject_template="[Report] {project_name} - {report_type} ({period})",
                html_template=_REPORT_HTML,
                text_template=_REPORT_TEXT,
                default_vars={
                    "project_name": "NexCoder Project",
                    "report_type": "Productivity & Quality Report",
                    "period": "Current Cycle",
                    "summary": "Engineering metrics and delivery performance summary.",
                    "metrics_summary": "All sprint tasks and deliverables verified.",
                    "recipient_name": "Team",
                    "sender_name": "Engineering Lead",
                },
            )
        )
        self.register(
            EmailTemplate(
                name="proposal_submission",
                description="Delivery of architectural jury evaluations, PRDs, and technical proposals.",
                subject_template="[Proposal] {proposal_title} - Verdict: {verdict}",
                html_template=_PROPOSAL_HTML,
                text_template=_PROPOSAL_TEXT,
                default_vars={
                    "proposal_title": "Architecture Specification",
                    "author": "Architectural Squad",
                    "verdict": "APPROVED",
                    "score": "8.5/10",
                    "executive_summary": "Architectural committee approved proposal with recommendations.",
                    "recipient_name": "Stakeholder",
                    "sender_name": "NexCoder Architecture Jury",
                },
            )
        )
        self.register(
            EmailTemplate(
                name="security_alert",
                description="Delivery of security scanner findings and release gate evaluations.",
                subject_template="[Security Alert] {project_name} - Gate: {gate_status}",
                html_template=_SECURITY_HTML,
                text_template=_SECURITY_TEXT,
                default_vars={
                    "project_name": "NexCoder Project",
                    "gate_status": "PASSED",
                    "critical_count": 0,
                    "high_count": 0,
                    "summary": "Automated security scanners evaluated release artifacts.",
                    "action_required": "Review attached findings report.",
                    "recipient_name": "Security Team",
                    "sender_name": "NexCoder Security Officer",
                },
            )
        )
        self.register(
            EmailTemplate(
                name="generic",
                description="Standard corporate announcement or report dispatch.",
                subject_template="{title}",
                html_template=_GENERIC_HTML,
                text_template=_GENERIC_TEXT,
                default_vars={
                    "title": "NexCoder Notification",
                    "recipient_name": "Colleague",
                    "body_content": "This is an automated notification from NexCoder.",
                    "sender_name": "NexCoder User",
                },
            )
        )

    def register(self, template: EmailTemplate) -> None:
        self._templates[template.name] = template

    def get(self, name: str) -> EmailTemplate | None:
        return self._templates.get(name)

    def list_templates(self) -> list[EmailTemplate]:
        return list(self._templates.values())

    def render(self, name: str, variables: dict[str, Any] | None = None) -> tuple[str, str, str]:
        tpl = self.get(name)
        if not tpl:
            raise KeyError(f"Email template '{name}' not found. Available: {list(self._templates.keys())}")
        return tpl.render(variables)
