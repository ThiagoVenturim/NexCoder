"""Reusable email templates for nexcoder reports, proposals, and governance alerts."""

from __future__ import annotations

import html
from typing import Any

from pydantic import BaseModel, Field


class EmailTemplate(BaseModel):
    """Template definition with HTML and plain-text layouts."""

    name: str
    description: str
    subject_template: str
    html_template: str
    text_template: str
    default_vars: dict[str, Any] = Field(default_factory=dict)

    def render(self, variables: dict[str, Any] | None = None) -> tuple[str, str, str]:
        """Render subject, HTML body, and plain-text body with variables."""
        merged = {**self.default_vars, **(variables or {})}

        # Safe HTML escaping for HTML variables
        escaped_vars = {}
        for k, v in merged.items():
            if isinstance(v, str):
                escaped_vars[k] = html.escape(v)
            else:
                escaped_vars[k] = v

        try:
            subject = self.subject_template.format(**merged)
        except KeyError as exc:
            subject = f"{self.subject_template} [missing var: {exc}]"

        try:
            body_html = self.html_template.format(**escaped_vars)
        except KeyError:
            # Fallback format with direct replacement
            body_html = self.html_template
            for k, val in escaped_vars.items():
                body_html = body_html.replace(f"{{{k}}}", str(val))

        try:
            body_text = self.text_template.format(**merged)
        except KeyError:
            body_text = self.text_template
            for k, val in merged.items():
                body_text = body_text.replace(f"{{{k}}}", str(val))

        return subject, body_html, body_text


